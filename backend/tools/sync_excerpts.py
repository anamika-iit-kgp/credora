"""Regenerate app/excerpts_code.py from the real Exasol scripts in the repo.

The backend image is built from ./backend only, so the code shown in each report's
"how Exasol decided" steps is copied here. Run after changing exasol/lua/06_run_analysis.sql:

    python backend/tools/sync_excerpts.py
"""

from __future__ import annotations

import pprint
import re
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LUA = ROOT / "exasol" / "lua" / "06_run_analysis.sql"
OUT = Path(__file__).resolve().parents[1] / "app" / "excerpts_code.py"

LUA_STEPS = {1, 8, 12}  # shown as Lua; the others are shown as the SQL they run
DECIDE_STEP = 11  # its SELECT lives in the CREDORA.DECISION_LOGIC library: shown joined to the INSERT
CHALLENGER_STEP = 13  # runs CREDORA.SCORE_CHALLENGER: shown as that script


def step_blocks(text: str) -> dict[int, str]:
    lines = text.splitlines()
    out: dict[int, str] = {}
    for i, line in enumerate(lines):
        m = re.match(r"step\((\d+),", line)
        if not m:
            continue
        j = i
        while lines[j] != "end)":
            j += 1
        start, end = i, j
        n = int(m.group(1))
        if n == 8:  # the active-model lookup around the step belongs to it
            start, end = i - 1, j + 1
        out[n] = "\n".join(lines[start:end + 1])
    return out


def sql_of(block: str) -> str:
    parts = re.findall(r"\[\[(.*?)\]\]", block, flags=re.S)
    stmts = []
    for p in parts:
        first, _, rest = p.partition("\n")
        body = textwrap.dedent(rest)
        stmts.append(((first.strip() + "\n") if first.strip() else "") + body.rstrip())
    return ";\n\n".join(s.strip("\n") for s in stmts) + ";"


def script_text(text: str, name: str) -> str:
    """The body of CREATE ... SCRIPT CREDORA.<name>, from the CREATE line to before the closing '/'."""
    lines = text.splitlines()
    i = next(k for k, l in enumerate(lines) if re.match(rf"CREATE OR REPLACE LUA SCRIPT CREDORA\.{name}\b", l))
    j = next(k for k in range(i, len(lines)) if lines[k].strip() == "/")
    return "\n".join(lines[i:j])


def decision_sql(text: str) -> str:
    """The decision SELECT inside CREDORA.DECISION_LOGIC."""
    body = re.search(r"\[\[\n(.*?)\]\]", script_text(text, "DECISION_LOGIC"), flags=re.S).group(1)
    return textwrap.dedent(body).rstrip()


def build(text: str) -> dict[int, tuple[str, str]]:
    code = {}
    for n, b in sorted(step_blocks(text).items()):
        if n == CHALLENGER_STEP:
            code[n] = ("lua", script_text(text, "SCORE_CHALLENGER"))
        elif n == DECIDE_STEP:
            code[n] = ("sql", sql_of(b).rstrip(";") + "\n" + decision_sql(text) + ";")
        else:
            code[n] = ("lua", b) if n in LUA_STEPS else ("sql", sql_of(b))
    return code


def main() -> None:
    code = build(LUA.read_text(encoding="utf-8"))
    OUT.write_text(
        '"""Generated by tools/sync_excerpts.py from exasol/lua/06_run_analysis.sql. Do not edit."""\n\n'
        "CODE: dict[int, tuple[str, str]] = " + pprint.pformat(code, width=120, sort_dicts=True) + "\n",
        encoding="utf-8")
    print(f"wrote {OUT} ({len(code)} steps)")


if __name__ == "__main__":
    main()
