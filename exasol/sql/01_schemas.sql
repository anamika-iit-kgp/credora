-- Credora schemas and tables in Exasol.
--   CREDORA        decisions, features, models, run log, policy
--   CREDORA_STAGE  raw replies from the external APIs, each row with a purge time

CREATE SCHEMA IF NOT EXISTS CREDORA_STAGE;
CREATE SCHEMA IF NOT EXISTS CREDORA;

-- Policy knobs used by the decision logic. The data scientist can change them (what-if).
CREATE TABLE IF NOT EXISTS CREDORA.CONFIG (
  CONFIG_KEY   VARCHAR(40) PRIMARY KEY,
  CONFIG_VALUE DECIMAL(12,4) NOT NULL,
  DESCRIPTION  VARCHAR(200)
);

MERGE INTO CREDORA.CONFIG c USING (
  SELECT 'EBLR_PCT' k, 8.25 v, 'External benchmark lending rate (repo-linked), % p.a.' d FROM DUAL UNION ALL
  SELECT 'OPERATING_SPREAD_PCT', 0.75, 'Operating spread added to every loan, % p.a.' FROM DUAL UNION ALL
  SELECT 'FUNDS_COST_PCT', 6.50, 'Cost of funds, % p.a.' FROM DUAL UNION ALL
  SELECT 'OPEX_PCT', 1.00, 'Operating cost, % of amount p.a.' FROM DUAL UNION ALL
  SELECT 'LGD_PCT', 45.00, 'Loss given default, %' FROM DUAL UNION ALL
  SELECT 'CAPITAL_PCT', 12.00, 'Capital held against the loan, % of amount' FROM DUAL UNION ALL
  SELECT 'HURDLE_PCT', 15.00, 'Minimum RAROC the bank accepts, %' FROM DUAL UNION ALL
  SELECT 'MAX_GST_SHARE_PCT', 20.00, 'Working capital cap as % of GST turnover' FROM DUAL UNION ALL
  SELECT 'MIN_DSCR', 1.25, 'Minimum debt service coverage at the offer' FROM DUAL UNION ALL
  SELECT 'NEGOTIATION_DSCR', 1.10, 'Minimum debt service coverage at the negotiation limit' FROM DUAL UNION ALL
  SELECT 'FLOOR_MARGIN_PCT', 0.50, 'Floor ROI is never below EBLR plus this, % p.a.' FROM DUAL UNION ALL
  SELECT 'ANOMALY_CONTAMINATION_PCT', 3.00, 'Share of companies the anomaly model flags for review, %' FROM DUAL
) s ON c.CONFIG_KEY = s.k
WHEN NOT MATCHED THEN INSERT VALUES (s.k, s.v, s.d);

CREATE TABLE IF NOT EXISTS CREDORA.RUN_LOG (
  RUN_ID       VARCHAR(20),
  STEP_NO      DECIMAL(3),
  STEP_NAME    VARCHAR(100),
  STATUS       VARCHAR(10),
  ROWS_OUT     DECIMAL(18),
  MS           DECIMAL(18),
  DETAIL       VARCHAR(2000),
  LOGGED_AT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- One row per application per run: the company joined across Oracle, MySQL and PostgreSQL.
CREATE TABLE IF NOT EXISTS CREDORA.APPLICATIONS (
  RUN_ID VARCHAR(20), APP_ID VARCHAR(8), CIF_ID VARCHAR(8), LEGAL_NAME VARCHAR(120), CONSTITUTION VARCHAR(30),
  PAN CHAR(10), GSTIN CHAR(15), INDUSTRY VARCHAR(40), CITY VARCHAR(40), STATE_NAME VARCHAR(30), RM_ID VARCHAR(6),
  KYC_STATUS VARCHAR(10), APPLIED_ON DATE, PRODUCT VARCHAR(4), AMOUNT_REQUESTED DECIMAL(18,2),
  TENURE_REQUESTED DECIMAL(4), PURPOSE VARCHAR(80), COLLATERAL_TYPE VARCHAR(30), COLLATERAL_VALUE DECIMAL(18,2),
  PARTNERS DECIMAL(2)
);

-- Company current-account activity per month, aggregated in Oracle through VS_CBS (pushdown).
CREATE TABLE IF NOT EXISTS CREDORA_STAGE.CA_MONTHLY (
  ACCOUNT_NO VARCHAR(14), CIF_ID VARCHAR(12), MON TIMESTAMP, CREDITS DECIMAL(18,2), DEBITS DECIMAL(10),
  BOUNCES DECIMAL(10), BAL_SUM DECIMAL(24,2), N DECIMAL(10)
);

CREATE TABLE IF NOT EXISTS CREDORA_STAGE.CIBIL_CONSUMER (
  RUN_ID VARCHAR(20), PAN CHAR(10), NAME VARCHAR(80), SCORE DECIMAL(4), ENQUIRIES_6M DECIMAL(4), ENQUIRIES_12M DECIMAL(4),
  ACCOUNTS DECIMAL(4), ACTIVE_ACCOUNTS DECIMAL(4), TOTAL_SANCTIONED DECIMAL(18,2), TOTAL_BALANCE DECIMAL(18,2),
  TOTAL_OVERDUE DECIMAL(18,2), MAX_DPD_12M DECIMAL(4), MAX_DPD_36M DECIMAL(4), WRITTEN_OFF DECIMAL(4),
  FETCHED_AT TIMESTAMP, PURGE_AT TIMESTAMP, RAW_JSON VARCHAR(200000)
);

CREATE TABLE IF NOT EXISTS CREDORA_STAGE.CIBIL_COMMERCIAL (
  RUN_ID VARCHAR(20), PAN CHAR(10), NAME VARCHAR(120), CMR_RANK DECIMAL(2), TOTAL_EXPOSURE DECIMAL(18,2),
  OVERDUE DECIMAL(18,2), SUIT_FILED BOOLEAN, WILFUL_DEFAULT BOOLEAN, FACILITIES DECIMAL(4),
  FETCHED_AT TIMESTAMP, PURGE_AT TIMESTAMP, RAW_JSON VARCHAR(20000)
);

CREATE TABLE IF NOT EXISTS CREDORA_STAGE.GST_FILING (
  RUN_ID VARCHAR(20), GSTIN CHAR(15), LEGAL_NAME VARCHAR(120), PAN CHAR(10), STATE_NAME VARCHAR(30), REGISTERED_ON DATE,
  REG_STATUS VARCHAR(10), STAGE VARCHAR(12), GST_PERIOD CHAR(7), GSTR1_TURNOVER DECIMAL(18,2), GSTR3B_TAX_PAID DECIMAL(18,2),
  DUE_DATE DATE, FILED_ON DATE, DELAY_DAYS DECIMAL(5), FETCHED_AT TIMESTAMP, PURGE_AT TIMESTAMP
);

CREATE TABLE IF NOT EXISTS CREDORA_STAGE.AA_ACCOUNT (
  RUN_ID VARCHAR(20), PAN CHAR(10), CONSENT_ID VARCHAR(36), CONSENT_EXPIRES TIMESTAMP, AA_ACCOUNT_ID VARCHAR(16),
  FIP VARCHAR(40), ACCT_TYPE VARCHAR(10), MASKED_NO VARCHAR(20), OPENED_ON DATE, CURRENT_BALANCE DECIMAL(18,2),
  TXN_COUNT DECIMAL(8), CREDITS_12M DECIMAL(18,2), DEBITS_12M DECIMAL(18,2), FETCHED_AT TIMESTAMP, PURGE_AT TIMESTAMP
);

-- Features exactly as defined in docs/DATA_MODEL.md section 8, plus the inputs pricing needs.
CREATE TABLE IF NOT EXISTS CREDORA.FEATURES (
  RUN_ID VARCHAR(20), APP_ID VARCHAR(8), CIF_ID VARCHAR(8),
  GST_YEARS DECIMAL(4,1), GST_TURNOVER_12M DECIMAL(18,2), GST_LATE_FILINGS_12M DECIMAL(3), GST_BANK_GAP_PCT DECIMAL(9,2),
  AVG_BALANCE_12M DECIMAL(18,2), INFLOW_VOLATILITY DECIMAL(9,4), BOUNCE_RATIO DECIMAL(9,4), CMR_RANK DECIMAL(2),
  PARTNER_MIN_SCORE DECIMAL(4), PARTNER_AVG_SCORE DECIMAL(6,1), PARTNER_OVERDUE_AMT DECIMAL(18,2),
  PARTNER_OTHER_BANK_BAL DECIMAL(18,2), DSCR DECIMAL(9,3),
  BANK_CREDITS_12M DECIMAL(18,2), WILFUL_DEFAULT BOOLEAN, SUIT_FILED BOOLEAN, GST_STAGE VARCHAR(12)
);

CREATE TABLE IF NOT EXISTS CREDORA.MODEL_REGISTRY (
  MODEL_VERSION VARCHAR(20), TRAINED_AT TIMESTAMP, ALGORITHM VARCHAR(80), AUC DECIMAL(6,4), GINI DECIMAL(6,4),
  N_TRAIN DECIMAL(10), DEFAULT_RATE DECIMAL(6,4), FEATURE_IMPORTANCE VARCHAR(20000), MODEL_PATH VARCHAR(200),
  IS_ACTIVE BOOLEAN
);

CREATE TABLE IF NOT EXISTS CREDORA.SCORES (
  RUN_ID VARCHAR(20), APP_ID VARCHAR(8), MODEL_VERSION VARCHAR(20), PD DECIMAL(9,6), GRADE VARCHAR(3),
  CONTRIBUTIONS VARCHAR(20000)
);

-- Champion/challenger: the challenger model's PD, grade and the decision it would have given, per
-- company. Written by CREDORA.SCORE_CHALLENGER; never read by the decision step.
CREATE TABLE IF NOT EXISTS CREDORA.CHALLENGER_SCORES (
  RUN_ID VARCHAR(20), APP_ID VARCHAR(8), MODEL_VERSION VARCHAR(20), PD DECIMAL(9,6), GRADE VARCHAR(3),
  DECISION VARCHAR(8)
);

-- Isolation Forest anomaly score per company (higher = more unusual). IS_ANOMALY marks the share set
-- by CONFIG ANOMALY_CONTAMINATION_PCT; flagged companies are referred, never declined, on it.
CREATE TABLE IF NOT EXISTS CREDORA.ANOMALY (
  RUN_ID VARCHAR(20), APP_ID VARCHAR(8), SCORE DECIMAL(9,6), IS_ANOMALY BOOLEAN, TOP_REASONS VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS CREDORA.DECISIONS (
  RUN_ID VARCHAR(20), APP_ID VARCHAR(8), CIF_ID VARCHAR(8), LEGAL_NAME VARCHAR(120), RM_ID VARCHAR(6),
  PRODUCT VARCHAR(4), AMOUNT_REQUESTED DECIMAL(18,2), TENURE_REQUESTED DECIMAL(4),
  DECISION VARCHAR(8), HARD_FAILS VARCHAR(2000), GRADE VARCHAR(3), PD DECIMAL(9,6),
  OFFER_AMOUNT DECIMAL(18,2), OFFER_ROI DECIMAL(6,3), OFFER_TENURE DECIMAL(4),
  FLOOR_ROI DECIMAL(6,3), MAX_AMOUNT DECIMAL(18,2), MAX_TENURE DECIMAL(4),
  RAROC_OFFER DECIMAL(9,3), RAROC_FLOOR DECIMAL(9,3), RANK_NO DECIMAL(5), SKYLINE_LAYER DECIMAL(4), TOP50 BOOLEAN,
  DECIDED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS CREDORA.PURGE_LOG (
  PURGED_AT TIMESTAMP, TABLE_NAME VARCHAR(60), RUN_ID VARCHAR(20), ROWS_DELETED DECIMAL(18), SHA256 CHAR(64)
);

-- Credit memos from CREDORA.CREDIT_MEMO (or the backend). MODEL holds '<model>|<engine>'.
CREATE TABLE IF NOT EXISTS CREDORA.MEMOS (
  RUN_ID VARCHAR(20), CIF_ID VARCHAR(8), MODEL VARCHAR(80), MEMO VARCHAR(20000), CREATED_AT TIMESTAMP
);
